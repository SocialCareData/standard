#!/usr/bin/env node
'use strict'

/*
 * Standard-agnostic SHACL example validator.
 *
 * Validates the JSON-LD examples that ship with each data standard under
 * src/assets/model/<standard>/ against the SHACL shapes generated from that
 * standard's LinkML schema. A standard may expose several conformance
 * *profiles* (e.g. the Person standard has "subject-of-care" and "connected"),
 * each with its own shape file and its own examples sub-folder.
 *
 * Files named valid-*.jsonld are expected to CONFORM; invalid-*.jsonld are
 * expected NOT to conform. Exit code is 0 when every example behaves as
 * expected, otherwise 1.
 *
 * Usage:
 *   node validate.js                        # every standard, every profile
 *   node validate.js person                 # one standard, all its profiles
 *   node validate.js person subject-of-care # one standard, one profile
 *   node validate.js person placements      # several standards
 */

const fs = require('fs')
const path = require('path')
const N3 = require('n3')
const jsonld = require('jsonld')
const rdf = require('rdf-ext').default
const SHACLValidator = require('rdf-validate-shacl').default

const MODEL_ROOT = path.resolve(__dirname, '..', '..', 'model')

// ---------------------------------------------------------------------------
// Standard registry
//
// Each standard lives in MODEL_ROOT/<dir> and declares one or more profiles.
// A profile pairs a generated SHACL shape file with a folder of examples.
// `crossChecks` names whole-set checks (see CROSS_CHECKS) that SHACL Core
// cannot express; they run once over all datasets in the standard.
// ---------------------------------------------------------------------------
const STANDARDS = {
  placements: {
    label: "Children's Social Care Placements",
    dir: 'placements',
    profiles: [
      {
        name: 'placements',
        // Multiple shape files are merged before validation. The base shape is
        // generated by gen-shacl; the rules shape is hand-maintained because
        // gen-shacl does not translate LinkML `rules:` into SHACL.
        shape: ['placements-standard-shape-01.ttl', 'placements-base-rules-shape.ttl'],
        examples: 'examples'
      }
    ],
    crossChecks: ['duplicateChildId']
  },
  person: {
    label: 'Person',
    dir: 'person',
    profiles: [
      {
        name: 'subject-of-care',
        shape: 'person-subject-of-care-shape.ttl',
        examples: 'examples/person-subject-of-care'
      },
      {
        name: 'connected',
        shape: 'person-connected-shape.ttl',
        examples: 'examples/person-connected'
      }
    ]
  }
}

// Whole-set checks that SHACL Core can't express. Each returns
// { ok: boolean, title: string, detail?: string }.
const CROSS_CHECKS = {
  // Duplicate childId across the set of placement records being validated.
  duplicateChildId (datasets) {
    const CHILD_ID = rdf.namedNode('https://ns.socialcaredata.io/placements/childId')
    const seen = new Map()
    for (const { file, dataset } of datasets) {
      for (const q of dataset.match(null, CHILD_ID, null)) {
        const id = q.object.value
        if (!seen.has(id)) seen.set(id, [])
        seen.get(id).push(file)
      }
    }
    const dups = [...seen.entries()].filter(([, files]) => files.length > 1)
    return {
      ok: dups.length === 0,
      title: 'duplicate childId',
      detail: dups.map(([id, files]) =>
        `childId=${id} in: ${files.map(f => path.basename(f)).join(', ')}`).join('\n  ')
    }
  }
}

// ---------------------------------------------------------------------------
// Terminal helpers
// ---------------------------------------------------------------------------
const COLOURS = {
  reset: '\x1b[0m', red: '\x1b[31m', green: '\x1b[32m',
  yellow: '\x1b[33m', cyan: '\x1b[36m', dim: '\x1b[2m', bold: '\x1b[1m'
}
const c = (col, s) => `${COLOURS[col]}${s}${COLOURS.reset}`

// ---------------------------------------------------------------------------
// RDF / JSON-LD loading
// ---------------------------------------------------------------------------
function parseTurtle (text) {
  return rdf.dataset(new N3.Parser().parse(text))
}

function parseNQuads (text) {
  return rdf.dataset(new N3.Parser({ format: 'application/n-quads' }).parse(text))
}

async function loadJsonLDFile (file) {
  const doc = JSON.parse(fs.readFileSync(file, 'utf8'))
  // Inline a relative @context so jsonld doesn't need a document loader.
  if (typeof doc['@context'] === 'string' && /^\.\.?\//.test(doc['@context'])) {
    const ctxPath = path.join(path.dirname(file), doc['@context'])
    doc['@context'] = JSON.parse(fs.readFileSync(ctxPath, 'utf8'))['@context']
  }
  const nquads = await jsonld.toRDF(doc, { format: 'application/n-quads' })
  return parseNQuads(nquads)
}

function listExamples (dir) {
  if (!fs.existsSync(dir)) return []
  return fs.readdirSync(dir)
    .filter(f => f.endsWith('.jsonld') && f !== 'context.jsonld' && !f.endsWith('-context.jsonld'))
    .sort()
    .map(f => path.join(dir, f))
}

// ---------------------------------------------------------------------------
// Reporting
// ---------------------------------------------------------------------------
function summariseResult (r) {
  return {
    sev: r.severity ? r.severity.value.split('#').pop() : 'Violation',
    path: r.path ? r.path.value : '(no path)',
    focus: r.focusNode ? r.focusNode.value : '(no focus)',
    msg: (r.message || []).map(m => m.value).join(' ; ') || '(no message)'
  }
}

function printReport (file, report) {
  const violations = report.results.filter(r => !r.severity || r.severity.value.endsWith('Violation'))
  const warnings = report.results.filter(r => r.severity && r.severity.value.endsWith('Warning'))
  const verdict = report.conforms
    ? c('green', 'CONFORMS')
    : (violations.length === 0 ? c('yellow', 'WARNINGS ONLY') : c('red', 'NON-CONFORMING'))

  console.log(`\n  ${c('bold', path.basename(file))}  ->  ${verdict}`)
  console.log(c('dim', `    violations=${violations.length}  warnings=${warnings.length}`))
  for (const r of report.results) {
    const s = summariseResult(r)
    const tag = s.sev === 'Warning' ? c('yellow', '    ! ') : c('red', '    X ')
    console.log(`${tag}[${s.sev}] ${s.path}`)
    console.log(c('dim', `        focus: ${s.focus}`))
    console.log(c('dim', `        ${s.msg}`))
  }
}

// ---------------------------------------------------------------------------
// Validation
// ---------------------------------------------------------------------------
async function validateProfile (std, profile) {
  const stdDir = path.join(MODEL_ROOT, std.dir)
  // A profile may declare one shape file or several (merged before validation).
  const shapeFiles = [].concat(profile.shape).map(s => path.join(stdDir, s))
  const examplesDir = path.join(stdDir, profile.examples)

  console.log(c('cyan', `\n=== ${std.label} / ${profile.name} ===`))

  const missing = shapeFiles.filter(f => !fs.existsSync(f))
  if (missing.length) {
    console.log(c('red', `  shape file missing: ${missing.map(f => path.relative(process.cwd(), f)).join(', ')}`))
    return { failures: 1, datasets: [] }
  }

  const shapes = rdf.dataset()
  for (const f of shapeFiles) shapes.addAll(parseTurtle(fs.readFileSync(f, 'utf8')))
  const validator = new SHACLValidator(shapes)
  const files = listExamples(examplesDir)
  if (!files.length) console.log(c('dim', `  (no examples in ${path.relative(process.cwd(), examplesDir)})`))

  let failures = 0
  const datasets = []
  for (const file of files) {
    let dataset
    try {
      dataset = await loadJsonLDFile(file)
    } catch (err) {
      console.error(`\n  ${c('red', 'ERROR')} loading ${path.basename(file)}: ${err.message}`)
      failures++
      continue
    }
    datasets.push({ file, dataset })

    const report = validator.validate(dataset)
    printReport(file, report)

    const expectValid = path.basename(file).startsWith('valid-')
    // A "valid" example must conform; an "invalid" one must have >=1 violation
    // (warnings alone still count as conforming).
    if (expectValid && !report.conforms) failures++
    if (!expectValid && report.conforms) failures++
  }
  return { failures, datasets }
}

async function validateStandard (std, profileFilter) {
  let failures = 0
  const allDatasets = []
  const profiles = profileFilter
    ? std.profiles.filter(p => p.name === profileFilter)
    : std.profiles

  if (!profiles.length) {
    console.log(c('red', `unknown profile '${profileFilter}' for standard`))
    return 1
  }

  for (const profile of profiles) {
    const res = await validateProfile(std, profile)
    failures += res.failures
    allDatasets.push(...res.datasets)
  }

  for (const name of std.crossChecks || []) {
    const check = CROSS_CHECKS[name]
    if (!check) continue
    const { ok, title, detail } = check(allDatasets)
    console.log(`\n  ${c('bold', `Cross-record check: ${title}`)}  ->  ${ok ? c('green', 'OK') : c('red', 'FAILED')}`)
    if (!ok) {
      if (detail) console.log(c('red', `  ${detail}`))
      failures++
    }
  }
  return failures
}

function parseArgs (argv) {
  const names = Object.keys(STANDARDS)
  if (!argv.length) return names.map(n => ({ standard: n }))
  // Several standard names: `validate.js person placements`
  if (argv.every(a => STANDARDS[a])) return argv.map(n => ({ standard: n }))
  // One standard, optional profile: `validate.js person subject-of-care`
  if (STANDARDS[argv[0]]) return [{ standard: argv[0], profileFilter: argv[1] }]
  return null
}

async function main () {
  const selections = parseArgs(process.argv.slice(2))
  if (!selections) {
    console.error(c('red', `Unknown standard. Available: ${Object.keys(STANDARDS).join(', ')}`))
    process.exit(2)
  }

  let failures = 0
  for (const { standard, profileFilter } of selections) {
    failures += await validateStandard(STANDARDS[standard], profileFilter)
  }

  console.log()
  if (failures === 0) {
    console.log(c('green', 'OK - all examples behaved as expected.'))
    process.exit(0)
  }
  console.log(c('red', `${failures} example(s)/check(s) did not match the expected outcome.`))
  process.exit(1)
}

main().catch(err => { console.error(err); process.exit(2) })
