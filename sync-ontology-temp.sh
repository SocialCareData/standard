#!/usr/bin/env bash
# TEMPORARY - delete once the ontology sync has run from main.
#
# Local equivalent of .github/workflows/ontology-sync.yml: regenerates the OWL,
# SHACL and aux files from the LinkML schemas at the current checkout and opens
# (or updates) a pull request on SocialCareData/ontology with whatever changed.
#
# Uses your own `gh` login instead of ONTOLOGY_SYNC_TOKEN, so you need push
# access to SocialCareData/ontology.
#
#   ./sync-ontology-temp.sh                 # build, push branch, open PR
#   DRY_RUN=1 ./sync-ontology-temp.sh       # build and show the diff only
#   BRANCH=my-branch ./sync-ontology-temp.sh
#
# BRANCH defaults to a fresh manual-sync-from-standard-<timestamp> branch, not
# the workflow's automation/sync-from-standard, so this does not overwrite the
# PR the workflow maintains for main.

set -euo pipefail

# Never stop at an interactive pager (less) waiting for "q".
export GIT_PAGER=cat PAGER=cat GH_PAGER=cat

ONTOLOGY_REPO=SocialCareData/ontology
STANDARD_REPO=SocialCareData/standard
BRANCH=${BRANCH:-manual-sync-from-standard-$(date +%Y%m%d-%H%M%S)}
DRY_RUN=${DRY_RUN:-0}
PYTHON=${PYTHON:-python3}

ROOT=$(cd "$(dirname "$0")" && pwd)
cd "$ROOT"

for cmd in git gh rsync "$PYTHON" gen-owl gen-shacl; do
  command -v "$cmd" >/dev/null || { echo "error: $cmd not found (pip install -r src/assets/scripts/requirements.txt for gen-*)" >&2; exit 1; }
done
gh auth status >/dev/null 2>&1 || { echo "error: run 'gh auth login' first" >&2; exit 1; }

SHA=$(git rev-parse HEAD)
SOURCE_BRANCH=$(git rev-parse --abbrev-ref HEAD)
if [ -n "$(git status --porcelain -- src/_data/model src/assets/scripts)" ]; then
  echo "warning: uncommitted changes under src/_data/model or src/assets/scripts are included in the build," >&2
  echo "         but the PR will reference $SHA, which does not contain them." >&2
fi
if ! git branch -r --contains "$SHA" 2>/dev/null | grep -q .; then
  echo "warning: $SHA is not pushed; the commit link in the PR body will 404 until it is." >&2
fi

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

echo "==> Generating ontology and shapes"
"$PYTHON" src/assets/scripts/build_ontology.py --out "$WORK/build"

ONTOLOGY_VERSION=$("$PYTHON" -c "import yaml;print(yaml.safe_load(open('src/_data/model/manifest.yaml'))['ontology_version'])")
echo "==> Ontology release: $ONTOLOGY_VERSION"

echo "==> Cloning $ONTOLOGY_REPO"
gh repo clone "$ONTOLOGY_REPO" "$WORK/ontology" -- --quiet

echo "==> Copying generated artifacts"
# Same rsync as the workflow: --delete so removed schemas disappear downstream,
# with the ontology repo's hand-written root files and workflows left alone.
rsync -a --delete \
  --exclude '.git/' \
  --exclude '/.github/' \
  --exclude '/README.md' \
  --exclude '/LICENSE' \
  "$WORK/build/" "$WORK/ontology/"

cd "$WORK/ontology"
git checkout -q -B "$BRANCH"
git add -A
if git diff --cached --quiet; then
  echo "No changes - the ontology repo is already up to date."
  exit 0
fi

echo "==> Changes:"
git diff --cached --stat

if [ "$DRY_RUN" = "1" ]; then
  echo "DRY_RUN=1: stopping before commit/push."
  exit 0
fi

git commit -q -m "Sync ontology from standard@$SHA" \
  -m "Generated by $STANDARD_REPO ($SOURCE_BRANCH) via sync-ontology-temp.sh."

echo "==> Pushing $BRANCH"
git push --force origin "$BRANCH"

PR_BODY="Regenerated from the LinkML schemas in
[$STANDARD_REPO](https://github.com/$STANDARD_REPO)
at [\`$SHA\`](https://github.com/$STANDARD_REPO/commit/$SHA) (branch \`$SOURCE_BRANCH\`).

- Ontology release: \`$ONTOLOGY_VERSION\`

> Generated files — review the diff, but make corrections in the
> LinkML YAML upstream rather than here."

url=$(gh pr list -R "$ONTOLOGY_REPO" --head "$BRANCH" --state open --json url --jq '.[0].url')
if [ -n "$url" ]; then
  echo "Updated existing PR: $url"
else
  gh pr create -R "$ONTOLOGY_REPO" --head "$BRANCH" --base main \
    --title "Sync ontology from standard ($SOURCE_BRANCH)" --body "$PR_BODY"
fi
